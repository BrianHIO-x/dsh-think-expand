def pick_font(kind: str) -> str:
    env_name = "DEMO_FONT_BOLD" if kind == "bold" else "DEMO_FONT_REGULAR"
    candidates = [
        os.environ.get(env_name),
        f"/usr/share/fonts/opentype/noto/NotoSansCJK-{'Bold' if kind == 'bold' else 'Regular'}.ttc",
        f"/usr/share/fonts/truetype/noto/NotoSansCJK-{'Bold' if kind == 'bold' else 'Regular'}.ttc",
        f"/usr/share/fonts/truetype/noto/NotoSansCJKsc-{'Bold' if kind == 'bold' else 'Regular'}.ttf",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    return ""


def validate_svg(markup: str) -> None:
    ET.fromstring(markup.encode("utf-8"))
    lowered = markup.lower()
    forbidden = (
        "<script", "<foreignobject", "<image", "href=", "xlink:href",
        "url(", "@import", "data:",
    )
    for token in forbidden:
        if token in lowered:
            raise RuntimeError(f"SVG contains forbidden token: {token}")
    if "viewBox=\"0 0 640 1390\"" not in markup:
        raise RuntimeError("SVG viewBox is missing")


def write_svg(path: Path) -> None:
    renderer = SvgRenderer()
    draw_scene(renderer)
    markup = renderer.finish()
    validate_svg(markup)
    path.write_text(markup, encoding="utf-8")
    print(f"wrote {path} ({len(markup):,} bytes)")


def write_png(path: Path, scale: int, font_regular: str, font_bold: str,
              font_index: int) -> None:
    if Image is None:
        raise RuntimeError("Pillow is not installed; skipping PNG")
    renderer = PillowRenderer(scale, font_regular, font_bold, font_index)
    draw_scene(renderer)
    image = renderer.finish()
    image.save(path, format="PNG", optimize=True)
    for warning in renderer.warnings:
        print(f"warning: {warning}", file=sys.stderr)
    print(f"wrote {path} ({image.width}x{image.height})")


