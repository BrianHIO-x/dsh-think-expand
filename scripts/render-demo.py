def gif_cursor(image, tip, scale: int = 2) -> None:
    """Draw a small white cursor with a dark outline at `tip` (1x coordinates)."""
    draw = ImageDraw.Draw(image)
    shape = [
        (0, 0), (0, 24), (6, 19), (12, 31),
        (18, 29), (12, 17), (21, 15),
    ]
    points = [
        (int((tip[0] + x * 0.9) * scale), int((tip[1] + y * 0.9) * scale))
        for x, y in shape
    ]
    draw.polygon(points, fill="#FFFFFF")
    draw.line(points + [points[0]], fill="#1F2A44", width=2 * scale)


def write_gif(path: Path, font_regular: str, font_bold: str,
              font_index: int) -> None:
    """A compact synthetic loop: hand-opened row, click the header switch, all open."""
    if Image is None:
        raise RuntimeError("Pillow is not installed; skipping GIF")
    scale = 2

    # Render the two card states at 2x, then crop the cards without captions.
    static = PillowRenderer(2, font_regular, font_bold, font_index)
    draw_scene(static)
    sheet = static.finish()
    card_a = sheet.crop((24 * scale, 174 * scale, 616 * scale, 618 * scale))
    card_b = sheet.crop((24 * scale, 688 * scale, 616 * scale, 1244 * scale))
    card_a_full = Image.new("RGB", card_b.size, PAGE_BG)
    card_a_full.paste(card_a, (0, 0))
    card_mid = Image.blend(card_a_full, card_b, 0.5)

    frames = []
    durations = []
    warnings: list[str] = []

    def add(card, on, duration, tip=None, ring=None):
        renderer = PillowRenderer(
            scale, font_regular, font_bold, font_index,
            width=GIF_W, height=GIF_H,
        )
        gif_page(renderer, on)
        image = renderer.finish()
        warnings.extend(renderer.warnings)
        image.paste(card, (24 * scale, 136 * scale))
        if ring is not None:
            radius, color = ring
            cx, cy = 552 * scale, 231 * scale
            width = max(2, 3 * scale)
            ImageDraw.Draw(image).ellipse(
                [cx - radius * scale, cy - radius * scale,
                 cx + radius * scale, cy + radius * scale],
                outline=color, width=width,
            )
        if tip is not None:
            gif_cursor(image, tip, scale)
        image = image.resize(
            (GIF_W, GIF_H), getattr(Image, "Resampling", Image).LANCZOS
        )
        frames.append(image)
        durations.append(duration)

    add(card_a, False, 2000)
    add(card_a, False, 120, tip=(612, 330))
    add(card_a, False, 140, tip=(610, 300))
    add(card_a, False, 320, tip=(584, 240), ring=(24, BLUE))
    add(card_mid, True, 120, tip=(584, 240), ring=(30, "#B9D0FF"))
    add(card_b, True, 2600)

    for warning in dict.fromkeys(warnings):
        print(f"warning: {warning}", file=sys.stderr)

    try:
        palette = frames[0].quantize(colors=128)
        quantized = [
            frame.quantize(palette=palette, dither=Image.Dither.NONE)
            for frame in frames
        ]
    except AttributeError:
        palette = frames[0].quantize(colors=128)
        quantized = [
            frame.quantize(palette=palette) for frame in frames
        ]
    quantized[0].save(
        path,
        format="GIF",
        save_all=True,
        append_images=quantized[1:],
        duration=durations,
        loop=0,
        disposal=2,
        optimize=True,
    )
    print(
        f"wrote {path} ({GIF_W}x{GIF_H}, {len(frames)} frames, "
        f"{path.stat().st_size:,} bytes)"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--formats", default="svg,png,gif",
        help="comma-separated subset of svg,png,gif (default: svg,png,gif)",
    )
    parser.add_argument(
        "--out-dir", default=None,
        help="output directory (default: docs next to this script)",
    )
    parser.add_argument(
        "--scale", type=int, default=2,
        help="PNG pixels per SVG unit (default: 2)",
    )
    parser.add_argument(
        "--font-regular", default="",
        help="regular CJK font path (default: auto-detect Noto Sans CJK)",
    )
    parser.add_argument(
        "--font-bold", default="",
        help="bold CJK font path (default: auto-detect Noto Sans CJK)",
    )
    parser.add_argument(
        "--font-index", type=int, default=2,
        help="TTC face index (default: 2, Noto Sans CJK SC)",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    formats = {item.strip().lower() for item in args.formats.split(",") if item.strip()}
    unknown = formats - {"svg", "png", "gif"}
    if unknown:
        print(f"unknown formats: {', '.join(sorted(unknown))}", file=sys.stderr)
        return 2
    if args.scale < 1:
        print("--scale must be at least 1", file=sys.stderr)
        return 2

    out_dir = Path(args.out_dir) if args.out_dir else Path(__file__).resolve().parent.parent / "docs"
    out_dir.mkdir(parents=True, exist_ok=True)

    if "svg" in formats:
        write_svg(out_dir / "demo.svg")

    if "png" in formats or "gif" in formats:
        if Image is None:
            print(
                "Pillow is not available; install it or rerun with --formats svg",
                file=sys.stderr,
            )
            return 1
        regular = args.font_regular or pick_font("regular")
        bold = args.font_bold or pick_font("bold")
        if not regular or not bold:
            print(
                "CJK fonts were not found; pass --font-regular and --font-bold",
                file=sys.stderr,
            )
            return 1
        if "png" in formats:
            write_png(
                out_dir / "demo.png", args.scale, regular, bold,
                args.font_index,
            )
        if "gif" in formats:
            write_gif(out_dir / "demo.gif", regular, bold, args.font_index)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
